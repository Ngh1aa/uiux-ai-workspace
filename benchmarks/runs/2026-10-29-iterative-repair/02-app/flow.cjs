'use strict';
module.exports = async function(page, assert) {
  const scenarios=[];
  assert.equal(await page.locator('main').getAttribute('data-role'),'player');
  await page.locator('#home [data-court="ky"][data-time="19:00"]').click();
  assert.equal(await page.locator('[data-detail-name]').innerText(),'Sân Kỳ Hoà');
  assert.match(await page.locator('[data-detail-price]').innerText(),/100\.000/);
  assert.equal(await page.locator('#detail [data-back]').getAttribute('href'),'#home');
  await page.locator('#detail [data-back]').click();
  assert.equal(await page.evaluate(()=>location.hash),'#home');
  scenarios.push({name:'correct object role and contextual back',status:'PASS'});
  await page.locator('#home [data-court="ky"][data-time="19:00"]').click();
  await page.locator('[data-open-booking]').click();
  await page.locator('#note').fill('Cần thuê 2 vợt');
  await page.locator('[data-step="1"]').click();
  assert.equal(await page.locator('[data-players]').innerText(),'5');
  await page.locator('[data-review-booking]').click();
  assert.equal(await page.locator('#review').isVisible(),true);
  assert.equal(await page.locator('[data-review-note]').innerText(),'Cần thuê 2 vợt');
  assert.match(await page.locator('[data-review-summary]').innerText(),/Sân Kỳ Hoà.*19:00.*5 người.*100\.000/);
  await page.locator('[data-confirm-action]').click();
  assert.equal(await page.locator('[data-race-error]').isVisible(),true);
  assert.equal(await page.locator('[data-review-booking]').getAttribute('aria-disabled'),'true');
  assert.match(await page.locator('#booking-reason').innerText(),/Chọn khung giờ khác/);
  assert.equal(await page.locator('#note').inputValue(),'Cần thuê 2 vợt');
  assert.equal(await page.locator('[data-players]').innerText(),'5');
  scenarios.push({name:'review before action and race failure retains input',status:'PASS'});
  await page.locator('[data-booking-time="21:00"]').click();
  await page.locator('[data-review-booking]').click();
  await page.locator('#review [data-close]').click();
  assert.equal(await page.locator('#review').isVisible(),false);
  await page.locator('[data-review-booking]').click();
  await page.locator('[data-confirm-action]').click();
  assert.equal(await page.evaluate(()=>location.hash),'#schedule');
  await page.locator('#schedule').waitFor({state:'visible'});
  assert.equal(await page.locator('[data-result]').isVisible(),true);
  assert.match(await page.locator('[data-result-summary]').innerText(),/Sân Kỳ Hoà.*23\/10.*21:00.*5 người.*100\.000/);
  assert.equal(await page.locator('[data-result-note]').innerText(),'Cần thuê 2 vợt');
  await page.goBack();
  assert.equal(await page.evaluate(()=>location.hash),'#booking');
  assert.equal(await page.locator('#note').inputValue(),'Cần thuê 2 vợt');
  assert.equal(await page.locator('[data-players]').innerText(),'5');
  await page.goForward();
  assert.equal(await page.evaluate(()=>location.hash),'#schedule');
  scenarios.push({name:'recover to valid time and consistent result; browser back preserves context',status:'PASS'});
  await page.locator('[data-edit]').click();
  assert.equal(await page.locator('#note').inputValue(),'Cần thuê 2 vợt');
  assert.equal(await page.locator('[data-players]').innerText(),'5');
  await page.locator('[data-step="-1"]').click();
  await page.locator('[data-review-booking]').click();
  await page.locator('[data-confirm-action]').click();
  assert.match(await page.locator('[data-result-summary]').innerText(),/4 người.*100\.000/);
  scenarios.push({name:'edit and reconfirm amount count note',status:'PASS'});
  await page.locator('[data-schedule="past"]').click();
  assert.equal(await page.locator('[data-past]').isVisible(),true);
  assert.equal(await page.locator('[data-result]').isVisible(),false);
  await page.locator('[data-schedule="upcoming"]').click();
  assert.equal(await page.locator('[data-result]').isVisible(),true);
  await page.locator('#schedule nav a[href="#courts"]').click();assert.equal(await page.locator('#courts button[data-court=ky][data-time="21:00"]').getAttribute('aria-pressed'),'true');assert.match(await page.locator('#courts [data-checkout-what]').innerText(),/Sân Kỳ Hoà.*21:00/);assert.equal(await page.locator('#courts button[data-court=ky][data-time="19:00"]').isDisabled(),true);assert.equal(await page.locator('#courts .app-pick').filter({has:page.locator('[data-court=ky]')}).locator('[data-availability]').innerText(),'Còn 1 khung trống tối nay');await page.locator('#courts #court-search').fill('Tân Định');
  assert.equal(await page.locator('#courts .app-pick:visible').count(),1);
  await page.locator('#courts #court-search').fill('Không có sân');
  assert.equal(await page.locator('#courts .app-pick:visible').count(),0);
  assert.equal(await page.locator('[data-search-empty]').isVisible(),true);
  await page.locator('[data-reset-search]').click();
  assert.equal(await page.locator('#courts .app-pick:visible').count(),3);
  scenarios.push({name:'schedule states and court search recover',status:'PASS'});
  return scenarios;
};
