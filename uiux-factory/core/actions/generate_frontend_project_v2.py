    @staticmethod
    def resolve_brand(
        design_system: DesignSystemContract,
        contract: DesignContract,
    ) -> tuple[str, str]:
        token = (
            design_system.foundations.colors.get(
                "color.brand.primary"
            )
        )

        if token and token.value:
            return str(token.value), token.status

        family = (
            contract.project.requested_primary_color
            or ""
        ).lower()

        fallback = {
            "purple": "#6C3BEF",
            "orange": "#E36D19",
            "red": "#C8323E",
            "green": "#168A4A",
            "blue": "#2864DC",
            "black": "#15131A",
        }.get(
            family,
            "#6C3BEF",
        )

        return fallback, "factory_default"

    @staticmethod
    def find_page(
        composition: VisualComposition,
        path: str,
    ) -> PageSpec:
        def normalize(value: str) -> str:
            if not value:
                return "/"

            normalized = "/" + value.strip("/")

            if normalized == "/":
                return "/"

            return normalized.lower()

        requested = normalize(path)

        # 1. Exact normalized route.
        for page in composition.pages:
            if normalize(page.path) == requested:
                return page

        # 2. Nested / dynamic route.
        prefix = requested.rstrip("/") + "/"

        for page in composition.pages:
            candidate = normalize(page.path)

            if candidate.startswith(prefix):
                return page

        # 3. Semantic route/page-role aliases.
        aliases = {
            "/category": (
                "category",
                "catalog",
                "catalogue",
                "collection",
                "browse",
                "listing",
                "shop",
                "products",
                "product listing",
            ),
            "/search": (
                "search",
                "find",
                "query",
                "results",
                "search results",
            ),
            "/cart": (
                "cart",
                "basket",
                "bag",
                "shopping cart",
            ),
            "/checkout": (
                "checkout",
                "payment",
                "order",
                "purchase",
                "transaction",
            ),
        }

        keywords = aliases.get(
            requested,
            (),
        )

        for page in composition.pages:
            haystack = " ".join(
                [
                    page.path or "",
                    page.page_role or "",
                    page.composition_family or "",
                ]
            ).lower()

            if any(
                keyword in haystack
                for keyword in keywords
            ):
                return page

        available = [
            {
                "path": page.path,
                "page_role": page.page_role,
                "composition_family": page.composition_family,
            }
            for page in composition.pages
        ]

        raise RuntimeError(
            "Visual Composition missing a route compatible with "
            f"{path}. Available pages: {available}"
        )

    @staticmethod
    def section_types(
        page: PageSpec,
    ) -> set[str]:
        return {
            section.type
            for section in page.sections
        }

    @classmethod
    def require_home_contract(
        cls,
        home: PageSpec,
    ) -> None:
        required = {
            "commerce-header": {"commerce-header"},
            "product-hero": {"editorial-product-hero", "product-hero"},
            "category-discovery": {"category-navigation", "category-discovery"},
            "merchandising": {"featured-products", "merchandising"},
            "commerce-proof": {"brand-proof", "commerce-proof"},
        }

        types = cls.section_types(home)
        missing = {role for role, aliases in required.items() if not aliases.intersection(types)}

        if missing:
            raise RuntimeError(
                "Visual Composition home contract incomplete. "
                f"Missing: {sorted(missing)}"
            )

