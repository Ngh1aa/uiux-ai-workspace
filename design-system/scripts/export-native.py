#!/usr/bin/env python3
"""Export native token files for SwiftUI and Jetpack Compose from generated/tokens.json.

    python3 design-system/scripts/export-native.py           # write generated/native/*
    python3 design-system/scripts/export-native.py --check   # fail if the files are stale

Only the semantic layer is exported (roles, not palette steps), following docs/platform-mapping.md:
colour roles in light and dark, spacing, shape, durations, easing curves and type roles mapped to the
platform's scalable text styles. Python standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "generated" / "tokens.json"
OUT = ROOT / "generated" / "native"
COLOR_GROUPS = ("surface", "text", "border", "action", "feedback", "dataviz", "media")
HEADER = "GENERATED by design-system/scripts/export-native.py from generated/tokens.json. Do not edit."

# Type role -> (iOS text style, Material 3 Typography slot), from docs/platform-mapping.md section 3.
TYPE_ROLES = {
    "display": (".largeTitle", "displaySmall"),
    "title-lg": (".title2", "headlineSmall"),
    "title-md": (".title3", "titleLarge"),
    "title-sm": (".headline", "titleMedium"),
    "body-lg": (".body", "bodyLarge"),
    "body-md": (".subheadline", "bodyMedium"),
    "body-sm": (".footnote", "bodySmall"),
    "label-lg": (".callout", "labelLarge"),
    "label-md": (".subheadline", "labelMedium"),
    "label-sm": (".caption", "labelSmall"),
}
WEIGHT_FILE = {"400": "Regular", "500": "Medium", "600": "SemiBold", "700": "Bold"}
WEIGHT_SWIFT = {"400": ".regular", "500": ".medium", "600": ".semibold", "700": ".bold"}

# Material 3 ColorScheme slot -> semantic role (docs/platform-mapping.md section 2).
M3_SCHEME = {
    "primary": "action.primary.bg",
    "onPrimary": "action.primary.text",
    "primaryContainer": "surface.brand-subtle",
    "onPrimaryContainer": "text.brand",
    "secondaryContainer": "action.secondary.bg",
    "onSecondaryContainer": "action.secondary.text",
    "background": "surface.page",
    "onBackground": "text.primary",
    "surface": "surface.page",
    "onSurface": "text.primary",
    "onSurfaceVariant": "text.secondary",
    "surfaceContainerLowest": "surface.raised",
    "surfaceContainerLow": "surface.raised",
    "surfaceContainer": "surface.raised",
    "surfaceContainerHigh": "surface.raised",
    "surfaceContainerHighest": "surface.sunken",
    "inverseSurface": "surface.inverse",
    "outline": "border.control",
    "outlineVariant": "border.subtle",
    "error": "action.danger.bg",
    "onError": "action.danger.text",
    "scrim": "surface.scrim",
}


def camel(path: str) -> str:
    parts = re.split(r"[.\-]", path)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(path: str) -> str:
    c = camel(path)
    return c[:1].upper() + c[1:]


def px(value: str) -> float:
    if value.endswith("rem"):
        return float(value[:-3]) * 16
    if value.endswith("px"):
        return float(value[:-2])
    raise ValueError(f"unexpected dimension {value}")


def ms(value: str) -> int:
    return int(float(value[:-2])) if value.endswith("ms") else int(float(value[:-1]) * 1000)


def num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else f"{v:g}"


def bezier(value: str) -> list[float]:
    return [float(x) for x in re.findall(r"-?[\d.]+", value)]


def load() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    return data["modes"]


def colour_roles(modes: dict) -> list[tuple[str, str, str]]:
    light, dark = modes["light"], modes["dark"]
    rows = []
    for key, tok in light.items():
        if tok.get("type") == "color" and key.split(".")[0] in COLOR_GROUPS:
            rows.append((key, tok["css"].lower(), dark[key]["css"].lower()))
    return sorted(rows)


def dims(modes: dict, prefix: str) -> list[tuple[str, float]]:
    out = []
    for key, tok in modes["light"].items():
        if key.startswith(prefix + ".") and tok.get("type") == "dimension":
            out.append((key[len(prefix) + 1:], px(tok["css"])))
    return out


def type_roles(modes: dict) -> list[tuple[str, float, float, str]]:
    out = []
    for role in TYPE_ROLES:
        t = modes["light"][f"type.{role}"]
        size = px(t["fontSize"])
        out.append((role, size, round(size * float(t["lineHeight"])), t["fontWeight"]))
    return out


def swift(modes: dict) -> str:
    L = [f"// {HEADER}", "// Mapping: design-system/docs/platform-mapping.md", "", "import SwiftUI", "import UIKit", ""]
    L += [
        "extension Color {",
        "    /// A colour that follows the system light or dark appearance.",
        "    init(dsLight light: UInt32, dark: UInt32) {",
        "        self.init(UIColor { trait in",
        "            let v = trait.userInterfaceStyle == .dark ? dark : light",
        "            return UIColor(red: CGFloat((v >> 16) & 0xff) / 255, green: CGFloat((v >> 8) & 0xff) / 255,",
        "                           blue: CGFloat(v & 0xff) / 255, alpha: 1)",
        "        })",
        "    }",
        "}",
        "",
        "public enum DS {",
        "    public enum Colors {",
    ]
    for key, lo, da in colour_roles(modes):
        L.append(f"        public static let {camel(key)} = Color(dsLight: 0x{lo[1:]}, dark: 0x{da[1:]})")
    L += ["    }", "", "    public enum Space {"]
    for name, v in dims(modes, "spacing"):
        L.append(f"        public static let {camel(name)}: CGFloat = {num(v)}")
    L += ["    }", "", "    /// Use with RoundedRectangle(cornerRadius:style: .continuous).", "    public enum Shape {"]
    for name, v in dims(modes, "shape"):
        L.append(f"        public static let {camel(name)}: CGFloat = {num(min(v, 999))}")
    L += ["    }", "", "    public enum Motion {"]
    for key, tok in modes["light"].items():
        if key.startswith("duration."):
            L.append(f"        public static let {camel(key)}: Double = {ms(tok['css']) / 1000:g}")
    for key, tok in modes["light"].items():
        if key.startswith("easing."):
            x1, y1, x2, y2 = bezier(tok["css"])
            L.append(f"        public static func {camel(key)}(_ duration: Double) -> Animation {{ .timingCurve({x1:g}, {y1:g}, {x2:g}, {y2:g}, duration: duration) }}")
    L += ["    }", "", "    /// Brand typeface that still scales with Dynamic Type.", "    public enum Fonts {"]
    for role, size, _lh, weight in type_roles(modes):
        style = TYPE_ROLES[role][0]
        L.append(f'        public static let {camel(role)} = Font.custom("BeVietnamPro-{WEIGHT_FILE[weight]}", size: {num(size)}, relativeTo: {style})')
    L += ["    }", "}", ""]
    return "\n".join(L)


def kotlin(modes: dict) -> str:
    rows = colour_roles(modes)
    L = [f"// {HEADER}", "// Mapping: design-system/docs/platform-mapping.md", "", "package design.system.tokens", ""]
    L += [
        "import androidx.compose.animation.core.CubicBezierEasing",
        "import androidx.compose.material3.ColorScheme",
        "import androidx.compose.material3.Typography",
        "import androidx.compose.material3.darkColorScheme",
        "import androidx.compose.material3.lightColorScheme",
        "import androidx.compose.runtime.Immutable",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.TextStyle",
        "import androidx.compose.ui.text.font.FontFamily",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "/** Every semantic colour role. Material slots cover only part of them; read the rest from here. */",
        "@Immutable",
        "data class DsColors(",
    ]
    L += [f"    val {camel(k)}: Color," for k, _, _ in rows]
    L += [")", "", "val LightDsColors = DsColors("]
    L += [f"    {camel(k)} = Color(0xFF{lo[1:].upper()})," for k, lo, _ in rows]
    L += [")", "", "val DarkDsColors = DsColors("]
    L += [f"    {camel(k)} = Color(0xFF{da[1:].upper()})," for k, _, da in rows]
    L += [")", "", "fun DsColors.toMaterialScheme(dark: Boolean): ColorScheme ="]
    args = ", ".join(f"{slot} = {camel(role)}" for slot, role in M3_SCHEME.items())
    L += [f"    if (dark) darkColorScheme({args})", f"    else lightColorScheme({args})", ""]
    L += ["object DsSpace {"]
    L += [f"    val {camel(n)} = {num(v)}.dp" for n, v in dims(modes, "spacing")]
    L += ["}", "", "object DsShape {"]
    L += [f"    val {camel(n)} = {num(min(v, 999))}.dp" for n, v in dims(modes, "shape")]
    L += ["}", "", "object DsMotion {"]
    for key, tok in modes["light"].items():
        if key.startswith("duration."):
            L.append(f"    const val {camel(key)} = {ms(tok['css'])}")
    for key, tok in modes["light"].items():
        if key.startswith("easing."):
            x1, y1, x2, y2 = bezier(tok["css"])
            L.append(f"    val {camel(key)} = CubicBezierEasing({x1:g}f, {y1:g}f, {x2:g}f, {y2:g}f)")
    L += ["}", "", "/** Pass FontFamily(Font(R.font.be_vietnam_pro_regular), …) from the app module. */",
          "fun dsTypography(family: FontFamily): Typography = Typography("]
    for role, size, lh, weight in type_roles(modes):
        slot = TYPE_ROLES[role][1]
        L.append(f"    {slot} = TextStyle(fontFamily = family, fontWeight = FontWeight.W{weight}, fontSize = {num(size)}.sp, lineHeight = {lh}.sp),")
    L += [")", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated/native is out of date")
    args = ap.parse_args()
    modes = load()
    files = {OUT / "DSTokens.swift": swift(modes), OUT / "DsTokens.kt": kotlin(modes)}
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            print("stale native tokens: " + ", ".join(str(p.relative_to(ROOT)) for p in stale)
                  + "; run python3 design-system/scripts/export-native.py", file=sys.stderr)
            return 1
        print(f"native tokens up to date ({len(files)} files)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in files.items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
