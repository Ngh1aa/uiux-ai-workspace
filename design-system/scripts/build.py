#!/usr/bin/env python3
"""Build DTCG tokens into CSS custom properties and a resolved JSON map.

    python3 design-system/scripts/build.py          # write generated/ files
    python3 design-system/scripts/build.py --check  # exit 1 if generated/ is stale

Aliases stay aliases in CSS (`var(--ds-...)`), so a dark-mode override of one semantic role
re-themes every component that references it. The JSON output is fully resolved per mode for
tools that cannot follow references (native handoff, Figma plugins, tests).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dslib import (ROOT, Token, TokenError, alias_target, color_hex, css_name,  # noqa: E402
                   load_config, mode_tokens, resolve)

HEADER = "/* GENERATED by design-system/scripts/build.py from tokens/*.json. Do not edit by hand. */\n"
TYPO_KEYS = {"fontFamily": "font-family", "fontSize": "font-size", "fontWeight": "font-weight",
             "lineHeight": "line-height", "letterSpacing": "letter-spacing"}


def fmt_number(n) -> str:
    return str(int(n)) if float(n).is_integer() else f"{n:g}"


def fmt_literal(ttype: str, v) -> str:
    if ttype == "color":
        hx = color_hex(v)
        alpha = v.get("alpha", 1)
        if alpha >= 1:
            return hx
        r, g, b = (int(hx[i:i + 2], 16) for i in (1, 3, 5))
        return f"rgb({r} {g} {b} / {fmt_number(alpha)})"
    if ttype in {"dimension", "duration"}:
        return f"{fmt_number(v['value'])}{v['unit']}"
    if ttype == "cubicBezier":
        return "cubic-bezier(" + ", ".join(fmt_number(x) for x in v) + ")"
    if ttype == "fontFamily":
        names = v if isinstance(v, list) else [v]
        generic = {"serif", "sans-serif", "monospace", "system-ui", "ui-monospace", "cursive", "fantasy"}
        return ", ".join(n if n in generic or n.startswith("-") else f'"{n}"' for n in names)
    if ttype in {"fontWeight", "number"}:
        return fmt_number(v)
    if ttype == "shadow":
        items = v if isinstance(v, list) else [v]
        parts = []
        for s in items:
            seg = " ".join(fmt_literal("dimension", s[k]) for k in ("offsetX", "offsetY", "blur", "spread"))
            parts.append(("inset " if s.get("inset") else "") + seg + " " + fmt_literal("color", s["color"]))
        return ", ".join(parts)
    raise TokenError(f"no CSS formatter for type '{ttype}'")


def css_value(tok: Token, ttype: str, prefix: str, member_types: dict) -> str:
    target = alias_target(tok.value)
    if target:
        return f"var({css_name(target, prefix)})"
    return fmt_literal(ttype, tok.value)


def css_decls(tokens: dict[str, Token], resolved: dict, prefix: str, only: set[str] | None = None) -> list[str]:
    lines = []
    for path, tok in tokens.items():
        if only is not None and path not in only:
            continue
        ttype = resolved[path][0]
        name = css_name(path, prefix)
        if ttype == "typography":
            target = alias_target(tok.value)
            for key, sub in TYPO_KEYS.items():
                if target:
                    val = f"var({css_name(target, prefix)}-{sub})"
                else:
                    member = tok.value[key]
                    ref = alias_target(member)
                    member_type = {"fontFamily": "fontFamily", "fontSize": "dimension", "fontWeight": "fontWeight",
                                   "lineHeight": "number", "letterSpacing": "dimension"}[key]
                    val = f"var({css_name(ref, prefix)})" if ref else fmt_literal(member_type, member)
                lines.append(f"  {name}-{sub}: {val};")
            continue
        lines.append(f"  {name}: {css_value(tok, ttype, prefix, {})};")
    return lines


def build() -> dict[str, str]:
    cfg = load_config()
    prefix = cfg["prefix"]
    modes = list(cfg["modes"])
    default = cfg["default_mode"]
    per_mode = {m: mode_tokens(m) for m in modes}
    resolved = {m: resolve(per_mode[m]) for m in modes}
    mode_paths = {m: {p for p, t in per_mode[m].items() if t.source in cfg["modes"][m]} for m in modes}

    css = [HEADER, ":root {", f"  color-scheme: {default};"]
    css += css_decls(per_mode[default], resolved[default], prefix)
    css.append("}\n")
    for m in modes:
        if m == default:
            continue
        decls = css_decls(per_mode[m], resolved[m], prefix, only=mode_paths[m])
        body = "\n".join([f"  color-scheme: {m};"] + decls)
        css.append(f"@media (prefers-color-scheme: {m}) {{\n  :root:not([data-theme=\"{default}\"]) {{\n"
                   + "\n".join("  " + line for line in body.splitlines()) + "\n  }\n}\n")
        css.append(f":root[data-theme=\"{m}\"] {{\n{body}\n}}\n")

    flat = {}
    for m in modes:
        flat[m] = {}
        for path, (ttype, val) in sorted(resolved[m].items()):
            if ttype == "typography":
                flat[m][path] = {k: fmt_literal({"fontFamily": "fontFamily", "fontSize": "dimension",
                                                  "fontWeight": "fontWeight", "lineHeight": "number",
                                                  "letterSpacing": "dimension"}[k], v) for k, v in val.items()}
            else:
                flat[m][path] = {"type": ttype, "css": fmt_literal(ttype, val)}
    out_json = json.dumps({"$comment": "GENERATED by design-system/scripts/build.py. Fully resolved values per mode.",
                           "prefix": prefix, "modes": flat}, indent=2, ensure_ascii=False) + "\n"
    from docs_page import render as render_docs
    docs = render_docs({m: resolved[m] for m in modes}, prefix, cfg["version"])
    return {cfg["outputs"]["css"]: "\n".join(css), cfg["outputs"]["json"]: out_json, cfg["outputs"]["docs"]: docs}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()
    try:
        outputs = build()
    except TokenError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    stale = []
    for rel, content in outputs.items():
        path = ROOT / rel
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if stale:
        print("ERROR: generated files are stale, run design-system/scripts/build.py: " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print(f"tokens build check passed ({len(outputs)} outputs up to date)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
